import * as Sentry from "@sentry/node";
import { env } from "./env.js";

/**
 * Ініціалізація Sentry. Імпортується **найпершим рядком** `app.ts` — до всього іншого.
 *
 * Без DSN не вмикається взагалі, тож локально нічого нікуди не летить: та сама домовленість, що з
 * поштою (`console`-транспорт) і лічильниками лімітів (MemoryStore).
 *
 * ## Що НЕ їде в Sentry — і чому це головна частина файлу
 *
 * Дефолти SDK зібрані під звичайний вебсервіс, а не під продукт зі щоденником. Кожна опція нижче
 * вимкнена навмисно, бо ввімкненою вона витягує з процесу те, чого там бути не повинно. Перелік не
 * з документації, а з типів встановленого SDK — онбординг згадує лише перші дві:
 *
 * - `stackFrameVariables` (дефолт `true`) — **найнебезпечніша**. Захоплює ЗНАЧЕННЯ локальних
 *   змінних у кадрах стеку: помилка при збереженні дня принесла б змінну з текстом нотатки, а
 *   помилка в auth — пароль. Саме про цю утечку попереджає roadmap.
 * - `httpBodies` — тіла запитів: `notes` щоденника, `password`, `code`, аватар.
 * - `cookies` (дефолт `true`) — access/refresh-токени на кожному запиті.
 * - `httpHeaders` (дефолт: збираються) — `Authorization`, `Cookie`, власні заголовки.
 * - `databaseQueryData` (дефолт `true`) — параметри й результати запитів Prisma, тобто той самий
 *   щоденник, лише з іншого боку.
 * - `userInfo` — жодних `email`/`ip_address`. Ідентифікатор користувача теж не чіпляємо: краще
 *   складніше зіставляти скарги з подіями, ніж тримати профіль людини в третьому сервісі.
 *
 * Підхід — «нічого, крім дозволеного»: кожен новий ендпоінт за замовчуванням закритий.
 *
 * **Перевірено, а не припущено** (2026-09-15, SDK 10.74): у подію підкладались канарки через тіло,
 * cookie, заголовок і query. Cookie й заголовки осідають лише в `sdkProcessingMetadata`, яке SDK
 * вирізає перед відправкою (`@sentry/core/envelope.js`), тобто процес вони не покидають. Локальних
 * змінних у кадрах не виявилось. А от query-рядок лишався в `request.url` попри `urlQueryParams:
 * false` — його прибирає `beforeSend` нижче.
 *
 * ## Чого тут немає
 *
 * **Трасування вимкнено** (`tracesSampleRate` не заданий). Воно шукає вузькі місця під
 * навантаженням, якого поки не існує, має власну квоту й тягне в події URL із параметрами.
 *
 * **ESM**: документація вимагає прапорець `--import`, бо без нього не працює авто-інструментація
 * OpenTelemetry. На Vercel запуском `node` ми не керуємо — платформа імпортує default-експорт з
 * `app.ts`. Перевірено, що для ЗАХОПЛЕННЯ ПОМИЛОК звичайного імпорту достатньо: SDK сам рапортує
 * «initialized from ESM» і події доходять. Втрачається лише трасування, якого ми й не вмикали.
 */
/**
 * Розгортання стектрейсів до `.ts`.
 *
 * У проді код виконується з `dist/*.js`, тож без цього рядка кадри в Sentry вказували б на
 * скомпільований файл — «`dist/lib/emailTokens.js:214`» замість «`src/lib/emailTokens.ts:107`».
 * Перевірено на зібраному `dist/`: різниця саме така.
 *
 * Програмний еквівалент прапорця `--enable-source-maps`, бо на Vercel запуском `node` ми не
 * керуємо — платформа імпортує застосунок сама. `.map` файли вже генерує `tsc` (`sourceMap: true`
 * у tsconfig), вивантажувати їх у Sentry не треба: Node розгортає трейс сам, ще до того, як SDK
 * його побачить.
 */
process.setSourceMapsEnabled(true);

Sentry.init({
  dsn: env.SENTRY_DSN,
  enabled: Boolean(env.SENTRY_DSN),
  environment: env.NODE_ENV,
  // Версія коду — щоб прив'язати помилку до конкретного деплою. Змінну виставляє Vercel; локально
  // її немає, і поле доводиться пропускати цілком: `release: undefined` SDK трактує як зламане
  // значення і глушить сесії («Discarded session because of missing or non-string release»).
  ...(process.env.VERCEL_GIT_COMMIT_SHA && { release: process.env.VERCEL_GIT_COMMIT_SHA }),
  dataCollection: {
    userInfo: false,
    httpBodies: [],
    cookies: false,
    httpHeaders: { request: false, response: false },
    urlQueryParams: false,
    databaseQueryData: false,
    stackFrameVariables: false,
  },
  /**
   * Остання сітка перед відправкою: зрізаємо query-рядок.
   *
   * `urlQueryParams: false` прибирає розібрані параметри, але сам `request.url` лишається цілим
   * разом із `?...`. Зараз чутливого в query немає (лише дати й пагінація), проте саме там
   * зазвичай і з'являються токени — а помітити це постфактум, уже з даними в чужому сервісі,
   * неможливо. Дешевше закрити наперед.
   */
  beforeSend(event) {
    if (event.request?.url) event.request.url = event.request.url.split("?")[0];
    return event;
  },
});
