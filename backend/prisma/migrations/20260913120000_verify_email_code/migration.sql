-- Підтвердження пошти переходить із посилання на 6-значний КОД, який людина вводить у застосунку.
--
-- Лічильник невдалих спроб — головний захист коду: 10^6 значень перебираються за хвилини, тож код
-- згорає після 5 промахів (VERIFY_CODE_MAX_ATTEMPTS у src/lib/emailTokens.ts). Для токенів із
-- посилання (32 байти ентропії) поле лишається 0 — там перебір не має сенсу.
ALTER TABLE "EmailToken" ADD COLUMN "attempts" INTEGER NOT NULL DEFAULT 0;

-- Невикористані токени СТАРОГО формату (довге посилання типу 'verify') після цієї міграції
-- неспоживні: код звіряється як sha256(userId:code), і такий рядок не збігтиметься ніколи.
-- Гасимо їх явно, щоб вони не перехоплювали пошук активного коду й не палили спроби людині,
-- яка просто ввела свіжий код із нового листа. Людина натомість просить новий код — лист із ним
-- надсилається тією ж кнопкою, що й раніше.
UPDATE "EmailToken" SET "usedAt" = NOW() WHERE "type" = 'verify' AND "usedAt" IS NULL;
