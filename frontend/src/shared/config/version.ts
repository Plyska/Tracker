/**
 * Версія застосунку — одне джерело на весь інтерфейс.
 *
 * Число приходить із `package.json` через `define` у `vite.config.ts`, тому підняти версію =
 * змінити один рядок у `package.json`. Раніше номер жив текстом у словниках (`uk.json`,
 * `en.json`), тобто в чотирьох місцях, які легко розʼїжджаються між мовами.
 *
 * Словники лишають за собою тільки форму підпису («Tellday v{{version}}»), бо вона перекладна,
 * а число — ні.
 */
export const APP_VERSION = __APP_VERSION__;

/**
 * Скорочений вигляд для згорнутого сайдбару: лише major.minor — у вузькій колонці патч-число
 * тільки з'їдає місце, а про виправлення користувачеві однаково нічого не каже.
 */
export const APP_VERSION_SHORT = APP_VERSION.split(".").slice(0, 2).join(".");
